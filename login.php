<?php
session_start();
require_once 'config/database.php';

// Redirect if already logged in
if (isLoggedIn()) {
    header('Location: ' . getBaseUrl() . '/dashboard.php');
    exit();
}

$error = '';

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $username = trim($_POST['username'] ?? '');
    $password = $_POST['password'] ?? '';
    
    if (empty($username) || empty($password)) {
        $error = 'Please enter both username and password.';
    } else {
        try {
            $pdo = getDB();
            $stmt = $pdo->prepare("SELECT user_id, full_name, username, password, role FROM users WHERE username = ?");
            $stmt->execute([$username]);
            $user = $stmt->fetch();
            
            if ($user && password_verify($password, $user['password'])) {
                // New session ID after login (prevents session fixation)
                session_regenerate_id(true);

                $_SESSION['user_id'] = $user['user_id'];
                $_SESSION['username'] = $user['username'];
                $_SESSION['full_name'] = $user['full_name'];
                $_SESSION['role'] = $user['role'];
                
                // Log login activity
                logActivity($pdo, $user['user_id'], 'LOGIN', 'users', 'User logged in');
                
                // Create a system backup of the login entry to preserve it even if user deletes account
                // This ensures we always have a record of who logged in, even after account deletion
                $pdo->exec("SET FOREIGN_KEY_CHECKS = 0");
                $stmt = $pdo->prepare("
                    INSERT INTO activity_log (user_id, action_type, table_name, description, timestamp) 
                    VALUES (0, 'LOGIN', 'users', ?, NOW())
                ");
                $stmt->execute([
                    "SYSTEM: [USER: {$user['username']} ({$user['full_name']})] User logged in"
                ]);
                $pdo->exec("SET FOREIGN_KEY_CHECKS = 1");
                
                header('Location: ' . getBaseUrl() . '/dashboard.php');
                exit();
            } else {
                $error = 'Invalid username or password.';
            }
        } catch (PDOException $e) {
            $error = 'Database error. Please try again.';
        }
    }
}
